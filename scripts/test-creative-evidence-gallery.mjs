import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import ts from 'typescript'
const read=p=>readFileSync(p,'utf8')
const page=read('src/app/espacio-creativo/page.tsx'),proxy=read('src/proxy.ts'),gallery=read('src/components/creative/CreativeGallery.tsx'),api=read('src/app/api/espacio-creativo/route.ts'),review=read('src/app/api/espacio-creativo/revision/route.ts'),edit=read('src/app/api/espacio-creativo/mis-obras/route.ts'),catalog=read('src/app/api/espacio-creativo/evidencias/route.ts'),admin=read('src/app/admin/espacio-creativo/page.tsx'),mine=read('src/components/creative/MyCreativeWorks.tsx')
assert.match(proxy,/pathname === '\/espacio-creativo'/)
assert.match(proxy,/pathname === '\/api\/espacio-creativo'/)
assert.match(proxy,/isPublicPath && \(!user \|\| legalOrAuthorizationPath\)/)
assert.match(page,/profile\.role === 'admin'/)
assert.match(gallery,/useState<Mode>\('mosaic'\)/)
assert.match(gallery,/\{canUpload && <button/)
assert.match(api,/new Set\(\['admin'\]\)/)
assert.match(api,/\.eq\('status', 'published'\)/)
assert.match(api,/eligiblePublicAuthors/)
assert.match(api,/\.range\(offset,offset\+99\)/)
assert.doesNotMatch(api,/\.limit\(80\)/)
assert.match(edit,/role\?\.role!=='admin'/)
assert.match(edit,/status: 'pending'/)
assert.match(review,/requireAdminSession\(\)/)
assert.match(review,/authorshipAndPermissionsVerified!==true/)
assert.match(review,/eligiblePublicAuthors/)
assert.match(review,/body\.action === 'restore'/)
assert.match(catalog,/await administrator\(\)/)
assert.match(catalog,/\.from\('evidences'\)/)
assert.match(catalog,/authorshipConfirmed!==true/)
assert.match(catalog,/db\.storage\.from\('evidencias'\)\.download/)
assert.match(catalog,/uploader_id:row\.created_by,author_name:author/)
assert.match(catalog,/status:'pending'/)
assert.match(admin,/CreativeAdminEdit/)
assert.match(admin,/CreativeEvidenceCatalog/)
assert.doesNotMatch(mine,/Editar mi obra/)
for(const p of ['src/app/espacio-creativo/page.tsx','src/components/creative/CreativeGallery.tsx','src/app/api/espacio-creativo/route.ts','src/app/api/espacio-creativo/revision/route.ts','src/app/api/espacio-creativo/mis-obras/route.ts','src/app/api/espacio-creativo/evidencias/route.ts','src/app/admin/espacio-creativo/page.tsx','src/components/creative/CreativeEvidenceCatalog.tsx','src/components/creative/CreativeAdminEdit.tsx','src/components/creative/MyCreativeWorks.tsx']){
 const result=ts.transpileModule(read(p),{fileName:p,reportDiagnostics:true,compilerOptions:{jsx:ts.JsxEmit.Preserve}})
 const errors=(result.diagnostics||[]).filter(x=>x.category===ts.DiagnosticCategory.Error)
 assert.equal(errors.length,0,p+': '+errors.map(x=>ts.flattenDiagnosticMessageText(x.messageText,' ')).join(', '))
}
console.log('OK: galería pública de lectura, permisos exclusivos del administrador, catálogo completo, autoría y revisión')

import {runInNewContext} from 'node:vm'
const helper={exports:{}}
